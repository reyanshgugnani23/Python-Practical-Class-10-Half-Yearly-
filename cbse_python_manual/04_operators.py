# CBSE Python reference: arithmetic, comparison, logical and assignment operators

# Arithmetic
print(10 + 20)
print(30 - 10)
print(5 * 6)
print(20 / 4)
print(20 // 3)
print(20 % 3)
print(2 ** 5)

# Comparison operators return True or False
print(20 > 10)
print(20 < 10)
print(5 == 5)
print(5 != 6)
print(45 >= 45)
print(13 <= 24)

# Logical operators
print(True and False)
print(True or False)
print(not False)

# Assignment operators
score = 10
score += 5
score *= 2
print(score)

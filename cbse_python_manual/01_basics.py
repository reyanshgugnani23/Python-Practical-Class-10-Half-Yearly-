# CBSE Python reference: statements, comments, variables and identifiers

# Assignment statement
number = 50

# Comment: comments begin with # and are ignored by Python
print(number)

# Multiple assignment
x, y, z = 5, 3.2, "Hello"
print(x)
print(y)
print(z)

# Same value assigned to multiple variables
a = b = c = "Python"
print(a, b, c)

# Case-sensitive identifiers
value = 10
Value = 20
print(value, Value)

# A useful multi-line expression using parentheses
result = (10 + 20 + 30 + 40)
print(result)
